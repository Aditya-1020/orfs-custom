"""Resolve and bundle explicitly enabled Tcl extensions."""
from __future__ import annotations

import os
from pathlib import Path
from typing import Any, Mapping, Sequence


class TclExtensionError(ValueError):
    """An explicitly configured Tcl extension is missing or invalid."""


def resolve_tcl_extensions(
    *,
    project_root: Path,
    flow_settings: Mapping[str, Any] | None = None,
    design_settings: Mapping[str, Any] | None = None,
    environ: Mapping[str, str] | None = None,
) -> list[Path]:
    """Resolve configured Tcl files; never discover or source files recursively."""
    env = os.environ if environ is None else environ
    configured: list[str] = []
    for settings in (flow_settings or {}, design_settings or {}):
        extensions = settings.get("extensions", {})
        if isinstance(extensions, Mapping):
            values = extensions.get("tcl", [])
            if isinstance(values, str):
                configured.append(values)
            elif isinstance(values, Sequence):
                configured.extend(str(value) for value in values)
    raw_env = env.get("ASICFLOW_TCL_EXTENSIONS", "")
    if raw_env:
        configured.extend(part for part in raw_env.split(os.pathsep) if part)

    resolved: list[Path] = []
    seen: set[Path] = set()
    for value in configured:
        path = Path(os.path.expanduser(os.path.expandvars(value)))
        if not path.is_absolute():
            path = project_root / path
        path = path.resolve()
        if path.suffix.lower() != ".tcl":
            raise TclExtensionError(f"Tcl extension must have a .tcl suffix: {path}")
        if not path.is_file():
            raise TclExtensionError(f"configured Tcl extension not found: {path}")
        if path not in seen:
            resolved.append(path)
            seen.add(path)
    return resolved


def _tcl_word(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace("{", "\\{").replace("}", "\\}")
    return "{" + escaped + "}"


def write_tcl_loader(output: Path | str, extensions: Sequence[Path]) -> Path | None:
    """Write a deterministic Tcl loader, returning None when no extensions exist."""
    if not extensions:
        return None
    path = Path(output)
    path.parent.mkdir(parents=True, exist_ok=True)
    words = " ".join(_tcl_word(str(item)) for item in extensions)
    lines = [
        "# Generated by asicflow. Edit the YAML configuration, not this file.",
        f"set ::asicflow_tcl_extensions [list {words}]",
        "foreach extension $::asicflow_tcl_extensions {",
        '    if {![file isfile $extension]} { error "Tcl extension not found: $extension" }',
        "    source $extension",
        "}",
        "",
    ]
    path.write_text("\n".join(lines))
    return path
