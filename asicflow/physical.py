from typing import Any

from .config import DEFAULT_MACROS, RunContext

PRESETS = {
    "lshape_left": {"side": "left", "gap": 20.0, "chan": 60.0},
    "lshape_right": {"side": "right", "gap": 20.0, "chan": 60.0},
}

# Heuristic thresholds — not a calibrated routing-success probability.
CONG_HARD_FAIL = 1.20
CONG_WEIGHT = 2.0
OVERFLOW_SOFT = 0.12
OVERFLOW_WEIGHT = 1.5
SCORE_PASS = 0.35

_GPL = {
    "cong_top_0_5": re.compile(r"GPL-0043\].*:\s*([0-9.]+)"),
    "cong_top_1_0": re.compile(r"GPL-0044\].*:\s*([0-9.]+)"),
    "cong_top_2_0": re.compile(r"GPL-0045\].*:\s*([0-9.]+)"),
    "cong_top_5_0": re.compile(r"GPL-0046\].*:\s*([0-9.]+)"),
    "cong_weighted": re.compile(r"GPL-0047\].*:\s*([0-9.]+)"),
}
_UTIL = re.compile(r"GPL-0019\]\s*Utilization:\s*([0-9.]+)\s*%")
_ITER = re.compile(
    r"^\s*\d+\s+\|\s+([0-9.]+)\s+\|\s+([0-9.]+(?:[eE][+\-]?\d+)?)\s+\|",
    re.M,
)
_GRT_TOTAL = re.compile(
    r"^Total\s+\d+\s+\d+\s+([0-9.]+)%\s+(\d+)\s*/\s*(\d+)\s*/\s*(\d+)\s*$",
    re.M,
)
_GRT_LAYER = re.compile(
    r"^(li1|met\d+)\s+(\d+)\s+(\d+)\s+([0-9.]+)%\s+(\d+)\s*/\s*(\d+)\s*/\s*(\d+)\s*$",
    re.M,
)
_GRT_FAIL = re.compile(r"GRT-0116")


def render_lshape_tcl(
    *,
    side: str,
    gap: float = 20.0,
    chan: float = 60.0,
    macros: tuple[str, ...] = DEFAULT_MACROS,
    name: str = "",
) -> str:
    if side not in ("left", "right"):
        raise ValueError("side must be 'left' or 'right'")
    if len(macros) != 3:
        raise ValueError("macros must be (wbuf, abuf, rbuf)")
    w, a, r = macros
    tag = name or f"lshape_{side}"
    return f"""# Generated by asicflow.physical — do not edit by hand.
# placement={tag}  side={side}  gap={gap}  chan={chan}
set ::blk [ord::get_db_block]
set ::dbu [$::blk getDbUnitsPerMicron]
proc um {{v}} {{ expr {{double($v) / $::dbu}} }}
proc msize {{n}} {{
  set m [[$::blk findInst $n] getMaster]
  list [um [$m getWidth]] [um [$m getHeight]]
}}
proc core {{}} {{
  set r [$::blk getCoreArea]
  list [um [$r xMin]] [um [$r yMin]] [um [$r xMax]] [um [$r yMax]]
}}

set ::W {{{w}}}
set ::A {{{a}}}
set ::R {{{r}}}
set ::gap  {float(gap)}
set ::chan {float(chan)}

lassign [core] x0 y0 x1 y1
puts "placement {tag}: core=$x0 $y0 $x1 $y1"
foreach m [list $::W $::A $::R] {{ puts "$m size: [msize $m]" }}

lassign [msize $::R] rw rh
lassign [msize $::W] ww wh
lassign [msize $::A] aw ah
set g $::gap
set cy [expr {{$y0 + $g + $rh + $::chan}}]
if {{"{side}" eq "left"}} {{
  set rx [expr {{$x1 - $g - $rw}}]; set r_or R0
  set cx [expr {{$x0 + $g}}];       set c_or MY
}} else {{
  set rx [expr {{$x0 + $g}}];       set r_or MY
  set cx [expr {{$x1 - $g - $aw}}]; set c_or R0
}}
if {{$rx < $x0 || $rx + $rw > $x1}} {{ error "lshape: rbuf does not fit core width" }}
if {{$cy + $ah + $g + $wh + $g > $y1}} {{ error "lshape: column does not fit core height" }}
place_macro -macro_name $::R -location [list $rx [expr {{$y0 + $g}}]] -orientation $r_or
place_macro -macro_name $::A -location [list $cx $cy]                  -orientation $c_or
place_macro -macro_name $::W -location [list $cx [expr {{$cy + $ah + $g}}]] -orientation $c_or
"""


def write_placement(
    ctx: RunContext,
    name: str,
    *,
    side: str,
    gap: float = 20.0,
    chan: float = 60.0,
    macros: tuple[str, ...] = DEFAULT_MACROS,
    generated: bool = True,
) -> Path:
    """Write placement Tcl. Presets → design-configs/placements/; customs → WORK_HOME/placements/."""
    out_dir = ctx.placements_generated if generated else ctx.placements_static
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{name}.tcl"
    path.write_text(
        render_lshape_tcl(side=side, gap=gap, chan=chan, macros=macros, name=name)
    )
    return path


def write_presets(ctx: RunContext) -> list[Path]:
    paths = []
    for name, opts in PRESETS.items():
        paths.append(
            write_placement(
                ctx,
                name,
                side=opts["side"],
                gap=opts["gap"],
                chan=opts["chan"],
                generated=False,
            )
        )
    return paths


# ---- placement routability heuristic --------------------------------------

@dataclass
class PredictionResult:
    routable: bool
    score: float
    model: str = "place_gp.heuristic_v1"
    notes: str = ""
    features: dict[str, Any] = field(default_factory=dict)

    def metric_rows(
        self, *, run_tag: str, stage: str = "3_place", corner: str = "-"
    ) -> list[tuple]:
        rows = [
            (run_tag, stage, corner, "predict", "routable", "1" if self.routable else "0", ""),
            (run_tag, stage, corner, "predict", "score", f"{self.score:.6g}", ""),
            (run_tag, stage, corner, "predict", "model", self.model, ""),
            (
                run_tag,
                stage,
                corner,
                "predict",
                "kind",
                "placement_routability_heuristic",
                "",
            ),
        ]
        if self.notes:
            rows.append((run_tag, stage, corner, "predict", "notes", self.notes, ""))
        for key, val in sorted(self.features.items()):
            rows.append((run_tag, stage, corner, "predict.feat", key, _fmt(val), ""))
        return rows


def _fmt(val: Any) -> str:
    return f"{val:.6g}" if isinstance(val, float) else str(val)


def _last_float(rx: re.Pattern[str], text: str) -> float | None:
    hits = rx.findall(text)
    return float(hits[-1]) if hits else None


def _all_floats(rx: re.Pattern[str], text: str) -> list[float]:
    return [float(x) for x in rx.findall(text)]


def parse_place_gp_log(path: Path) -> dict[str, Any]:
    if not path.is_file():
        return {}
    text = path.read_text(errors="replace")
    out: dict[str, Any] = {"place_gp_log": str(path)}
    util = _last_float(_UTIL, text)
    if util is not None:
        out["gp_util_pct"] = util
    for key, rx in _GPL.items():
        vals = _all_floats(rx, text)
        if not vals:
            continue
        out[f"gp_{key}_last"] = vals[-1]
        out[f"gp_{key}_min"] = min(vals)
        out[f"gp_{key}_max"] = max(vals)
    iters = _ITER.findall(text)
    if iters:
        overflow, hpwl = iters[-1]
        out["gp_overflow_final"] = float(overflow)
        out["gp_hpwl_final_um"] = float(hpwl)
    return out


def parse_grt_log(path: Path) -> dict[str, Any]:
    if not path.is_file():
        return {}
    text = path.read_text(errors="replace")
    out: dict[str, Any] = {
        "grt_log": str(path),
        "grt_failed": bool(_GRT_FAIL.search(text)),
    }
    m = _GRT_TOTAL.search(text)
    if m:
        out["grt_usage_pct"] = float(m.group(1))
        out["grt_max_h_overflow"] = int(m.group(2))
        out["grt_max_v_overflow"] = int(m.group(3))
        out["grt_total_overflow"] = int(m.group(4))
    for lm in _GRT_LAYER.finditer(text):
        layer = lm.group(1)
        out[f"grt_{layer}_usage_pct"] = float(lm.group(4))
        out[f"grt_{layer}_overflow"] = int(lm.group(7))
    return out


def metrics_features(
    db: Path | None, *, run_tag: str, platform: str = "", stage: str = "3_place"
) -> dict[str, Any]:
    if not db or not db.is_file():
        return {}
    keys = (
        ("design", "util_all_pct"),
        ("design", "util_std_excl_macro_pct"),
        ("design", "inst_std_count"),
        ("net", "hpwl_total_um"),
        ("timing", "setup_ws"),
    )
    out: dict[str, Any] = {}
    con = sqlite3.connect(db)
    try:
        for cat, metric in keys:
            if platform:
                row = con.execute(
                    "SELECT value FROM metrics WHERE run_tag=? AND platform=? AND stage=? "
                    "AND category=? AND metric=? ORDER BY collected_at DESC LIMIT 1",
                    (run_tag, platform, stage, cat, metric),
                ).fetchone()
            else:
                row = con.execute(
                    "SELECT value FROM metrics WHERE run_tag=? AND stage=? AND category=? "
                    "AND metric=? ORDER BY collected_at DESC LIMIT 1",
                    (run_tag, stage, cat, metric),
                ).fetchone()
            if not row:
                continue
            try:
                out[f"db_{cat}_{metric}"] = float(row[0])
            except (TypeError, ValueError):
                out[f"db_{cat}_{metric}"] = row[0]
    finally:
        con.close()
    return out


def extract_features(
    *,
    odb_path: Path,
    logs_dir: Path | None = None,
    reports_dir: Path | None = None,
    metrics_db: Path | None = None,
    run_tag: str = "",
    platform: str = "",
) -> dict[str, Any]:
    feats: dict[str, Any] = {
        "odb_exists": odb_path.is_file(),
        "odb_bytes": odb_path.stat().st_size if odb_path.is_file() else 0,
    }
    if logs_dir:
        feats.update(parse_place_gp_log(logs_dir / "3_3_place_gp.log"))
        feats.update(parse_grt_log(logs_dir / "5_1_grt.log"))
    if reports_dir and (reports_dir / "congestion.rpt").is_file():
        n = sum(
            1
            for ln in (reports_dir / "congestion.rpt").read_text(errors="replace").splitlines()
            if ln.startswith("violation type:")
        )
        feats["congestion_rpt_violations"] = n
    if run_tag:
        feats.update(
            metrics_features(metrics_db, run_tag=run_tag, platform=platform)
        )
    return feats


def predict_routable(features: dict[str, Any]) -> PredictionResult:
    """Placement routability heuristic using final GP congestion, not the min."""
    # Prefer the last (final) weighted congestion measurement from global placement.
    cong = features.get("gp_cong_weighted_last", features.get("gp_cong_weighted_min"))
    overflow = features.get("gp_overflow_final")
    util = features.get("gp_util_pct", features.get("db_design_util_all_pct"))

    missing = [
        n
        for n, v in (("gp_cong_weighted", cong), ("gp_overflow_final", overflow))
        if v is None
    ]
    if missing:
        return PredictionResult(
            routable=False,
            score=0.0,
            notes=f"missing {','.join(missing)}; need 3_3_place_gp.log",
            features=features,
        )

    cong_f = float(cong)
    overflow_f = float(overflow)
    notes = f"cong_final={cong_f:.4f} overflow={overflow_f:.4f}"
    if util is not None:
        notes += f" util={float(util):.2f}%"
    if features.get("grt_failed"):
        notes += f"; grt_total_overflow={features.get('grt_total_overflow', '?')}"

    if cong_f >= CONG_HARD_FAIL:
        return PredictionResult(
            routable=False,
            score=0.0,
            notes=notes + f" (cong>={CONG_HARD_FAIL})",
            features=features,
        )

    risk = max(0.0, cong_f - 1.0) * CONG_WEIGHT
    risk += max(0.0, overflow_f - OVERFLOW_SOFT) * OVERFLOW_WEIGHT
    score = max(0.0, min(1.0, 1.0 - risk))
    return PredictionResult(
        routable=score >= SCORE_PASS,
        score=score,
        notes=notes,
        features=features,
    )


def run_prediction(
    *,
    odb_path: Path,
    run_tag: str,
    logs_dir: Path | None = None,
    reports_dir: Path | None = None,
    metrics_db: Path | None = None,
    out_json: Path | None = None,
    stage: str = "3_place",
    platform: str = "",
) -> PredictionResult:
    if not odb_path.is_file():
        raise FileNotFoundError(
            f"place ODB missing: {odb_path} (make place RUN_TAG={run_tag})"
        )
    result = predict_routable(
        extract_features(
            odb_path=odb_path,
            logs_dir=logs_dir,
            reports_dir=reports_dir,
            metrics_db=metrics_db,
            run_tag=run_tag,
            platform=platform,
        )
    )
    if out_json is not None:
        out_json.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "run_tag": run_tag,
            "platform": platform,
            "stage": stage,
            "odb": str(odb_path),
            "kind": "placement_routability_heuristic",
            "collected_at": datetime.now(timezone.utc)
            .replace(microsecond=0)
            .isoformat(),
            **asdict(result),
        }
        out_json.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    return result

